let firstName = 'Klew'; // js variables are written in camel case
let lastName = 'Kaine';

console.log(firstName); // the variable is printed to the console
console.log(lastName);

let age = 45;
console.log(age);

age = 30; // the 'age' variable is assigned the value of 30. no need for 'let' since the variable was already declared

console.log(age); // 30 is printed to the console instead of 45

const pi = 3.14; // the 'const' keyword creates an unchangeable variable
pi = 10;

console.log(pi); // returns an error since the variable can't be re-assigned a different value